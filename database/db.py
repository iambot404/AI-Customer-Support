def create_user(username: str, email: str, password_hash: str, role: str = "agent"):
    now = datetime.now(timezone.utc).isoformat()
    sql = _format_sql("""
        INSERT INTO users (username, email, password_hash, role, created_at)
        VALUES (?, ?, ?, ?, ?)
    """)
    with get_db() as conn:
        cursor = conn.cursor()
        cursor.execute(sql, (username.strip(), email.strip().lower(), password_hash, role, now))
        user_id = cursor.lastrowid if hasattr(cursor, 'lastrowid') and cursor.lastrowid else None
        if not user_id and is_postgres():
            cursor.execute("SELECT LASTVAL() AS id")
            row = cursor.fetchone()
            user_id = row['id'] if isinstance(row, dict) else row[0]
        return user_id


