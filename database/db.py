import os
import sqlite3
from datetime import datetime, timezone
from contextlib import contextmanager
from config import Config

# Optional PostgreSQL driver support
try:
    import psycopg2
    from psycopg2.extras import RealDictCursor
    POSTGRES_AVAILABLE = True
except ImportError:
    POSTGRES_AVAILABLE = False


def get_database_url():
    try:
        from flask import current_app, has_app_context
        if has_app_context():
            return current_app.config.get("DATABASE_URL", Config.DATABASE_URL)
    except Exception:
        pass
    return Config.DATABASE_URL


def get_sqlite_path():
    try:
        from flask import current_app, has_app_context
        if has_app_context():
            return current_app.config.get("SQLITE_PATH", Config.SQLITE_PATH)
    except Exception:
        pass
    return Config.SQLITE_PATH


def is_postgres():
    db_url = get_database_url()
    return bool(db_url and db_url.startswith(("postgres://", "postgresql://")))


@contextmanager
def get_db():
    """Context manager providing a database connection and cursor."""
    if is_postgres():
        if not POSTGRES_AVAILABLE:
            raise RuntimeError("PostgreSQL DATABASE_URL provided but psycopg2 is not installed.")
        db_url = get_database_url()
        if db_url.startswith("postgres://"):
            db_url = "postgresql://" + db_url[len("postgres://"):]
        conn = psycopg2.connect(db_url, cursor_factory=RealDictCursor)
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()
    else:
        conn = sqlite3.connect(get_sqlite_path())
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON;")
        try:
            yield conn
            conn.commit()
        except Exception:
            conn.rollback()
            raise
        finally:
            conn.close()


def get_connection():
    """Direct connection helper for test cases or custom scripts."""
    if is_postgres():
        return psycopg2.connect(get_database_url())
    conn = sqlite3.connect(get_sqlite_path())
    conn.row_factory = sqlite3.Row
    return conn


def _format_sql(sql: str) -> str:
    """Adapts query parameter syntax: ? for SQLite, %s for PostgreSQL."""
    if is_postgres():
        return sql.replace("?", "%s")
    return sql


def _row_to_dict(row):
    if row is None:
        return None
    if isinstance(row, dict):
        return dict(row)
    return {k: row[k] for k in row.keys()}


def init_db():
    """Initializes schema if not already present."""
    with get_db() as conn:
        cursor = conn.cursor()
        if is_postgres():
            cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT DEFAULT 'agent',
                created_at TEXT NOT NULL
            );
            """)
            cursor.execute("""
            CREATE TABLE IF NOT EXISTS tickets (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_name TEXT,
                customer_email TEXT,
                subject TEXT NOT NULL,
                message TEXT NOT NULL,
                category TEXT,
                priority TEXT,
                ai_category TEXT,
                ai_priority TEXT,
                ai_summary TEXT,
                ai_reason TEXT,
                confidence REAL,
                status TEXT NOT NULL DEFAULT 'Open',
                classification_status TEXT NOT NULL DEFAULT 'Pending',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            );
            """)
        else:
            cursor.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT UNIQUE NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password_hash TEXT NOT NULL,
                role TEXT DEFAULT 'agent',
                created_at TEXT NOT NULL
            );
            """)
            cursor.execute("""
            CREATE TABLE IF NOT EXISTS tickets (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                customer_name TEXT,
                customer_email TEXT,
                subject TEXT NOT NULL,
                message TEXT NOT NULL,
                category TEXT,
                priority TEXT,
                ai_category TEXT,
                ai_priority TEXT,
                ai_summary TEXT,
                ai_reason TEXT,
                confidence REAL,
                status TEXT NOT NULL DEFAULT 'Open',
                classification_status TEXT NOT NULL DEFAULT 'Pending',
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL
            );
            """)


